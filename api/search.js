const { Pool } = require('pg');

const SEARCH_COLUMNS =
  'id, fname, lname, nationalid, location, documentname, contactnumber, containernumber';

let pool;
let schemaReady;

function getPool() {
  if (!pool) {
    const connectionString =
      process.env.DATABASE_URL ||
      process.env.NEON_DATABASE_URL ||
      process.env.POSTGRES_URL;

    if (!connectionString) {
      throw new Error(
        'Missing database URL. Set DATABASE_URL in the Vercel project environment variables.'
      );
    }

    pool = new Pool({
      connectionString,
      max: 5,
      idleTimeoutMillis: 30_000,
      connectionTimeoutMillis: 10_000,
    });
  }
  return pool;
}

async function query(sql, params = []) {
  const { rows } = await getPool().query(sql, params);
  return rows;
}

function ensureSchema() {
  if (!schemaReady) {
    schemaReady = query(`
      CREATE TABLE IF NOT EXISTS collected (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        original_id BIGINT NOT NULL UNIQUE,
        fname VARCHAR(255),
        lname VARCHAR(255),
        nationalid VARCHAR(255),
        location VARCHAR(255),
        documentname VARCHAR(255),
        contactnumber VARCHAR(255),
        containernumber INTEGER NOT NULL DEFAULT 0,
        collected_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `).catch((err) => {
      schemaReady = null;
      throw err;
    });
  }
  return schemaReady;
}

async function searchByCriterion(documentname, column, value) {
  if (!value || !String(value).trim()) return [];

  return query(
    `SELECT ${SEARCH_COLUMNS}, 'Available' AS status, NULL::timestamptz AS collected_at
       FROM savings
      WHERE LOWER(documentname) = LOWER($1) AND LOWER(${column}) = LOWER($2)
     UNION ALL
     SELECT ${SEARCH_COLUMNS}, 'Collected' AS status, collected_at
       FROM collected
      WHERE LOWER(documentname) = LOWER($1) AND LOWER(${column}) = LOWER($2)`,
    [documentname, value]
  );
}

module.exports = async function handler(req, res) {
  if (req.method !== 'GET') {
    res.setHeader('Allow', 'GET');
    return res.status(405).json({ error: 'Method not allowed.' });
  }

  try {
    await ensureSchema();
    const { documentname, nationalid, fname, lname } = req.query || {};

    const rows = [
      ...(await searchByCriterion(documentname, 'nationalid', nationalid)),
      ...(await searchByCriterion(documentname, 'fname', fname)),
      ...(await searchByCriterion(documentname, 'lname', lname)),
    ];

    const seen = new Set();
    const users = rows.filter((row) => {
      const key = `${row.status}-${row.id}`;
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    });

    if (users.length === 0) {
      return res.json({
        error: 'No results found for this document type and search criteria.',
        users: [],
      });
    }

    return res.json({ users });
  } catch (err) {
    console.error(err);
    return res.status(500).json({ error: 'Search failed.' });
  }
};
