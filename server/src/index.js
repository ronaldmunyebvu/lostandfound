import express from 'express';
import cors from 'cors';
import path from 'path';
import { fileURLToPath } from 'url';
import { pool, query } from './db.js';
import { searchUsers } from './userService.js';

const app = express();
const PORT = process.env.PORT || 5000;

app.use(
  cors({
    origin: process.env.CLIENT_ORIGIN || 'http://localhost:5173',
  })
);
app.use(express.json());
app.use(express.urlencoded({ extended: true }));

let schemaReady;

function ensureSchema() {
  if (!schemaReady) {
    schemaReady = query(`
      CREATE TABLE IF NOT EXISTS collected (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        original_id BIGINT NOT NULL UNIQUE,
        fname VARCHAR(255),
        lname VARCHAR(255),
        nationalid VARCHAR(255),
        location VARCHAR(255),
        documentname VARCHAR(255),
        contactnumber VARCHAR(255),
        containernumber INTEGER NOT NULL DEFAULT 0,
        collected_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `).catch((err) => {
      schemaReady = null;
      throw err;
    });
  }
  return schemaReady;
}

app.get('/api/health', (_req, res) => res.json({ status: 'ok' }));

// Public search only. Admin actions live in the separate super admin app.
app.get('/api/search', async (req, res) => {
  try {
    await ensureSchema();
    const { documentname, nationalid, fname, lname } = req.query;
    const users = await searchUsers(documentname, nationalid, fname, lname);

    if (users.length === 0) {
      return res.json({
        error: 'No results found for this document type and search criteria.',
        users: [],
      });
    }
    return res.json({ users });
  } catch (err) {
    console.error(err);
    return res.status(500).json({ error: 'Search failed.' });
  }
});

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const clientDist = path.join(__dirname, '../../client/dist');
app.use(express.static(clientDist));
app.get(/^(?!\/api).*/, (_req, res) => {
  res.sendFile(path.join(clientDist, 'index.html'));
});

app.listen(PORT, () => {
  console.log(`Public Lost & Found site running on http://localhost:${PORT}`);
  ensureSchema()
    .then(() => pool.query('SELECT 1'))
    .catch((err) => {
      console.error('PostgreSQL connection error:', err.message);
    });
});
