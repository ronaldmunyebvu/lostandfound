import dotenv from 'dotenv';
import pg from 'pg';
import { fileURLToPath } from 'url';

dotenv.config({ path: fileURLToPath(new URL('../../.env', import.meta.url)) });

async function init() {
  const connectionString =
    process.env.DATABASE_URL ||
    process.env.NEON_DATABASE_URL ||
    process.env.POSTGRES_URL;
  if (!connectionString) {
    throw new Error(
      'Missing database URL. Set DATABASE_URL in the project-root .env file.'
    );
  }

  const pool = new pg.Pool({ connectionString, allowExitOnIdle: true });
  await pool.query(`
    CREATE TABLE IF NOT EXISTS savings (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      fname VARCHAR(255),
      lname VARCHAR(255),
      nationalid VARCHAR(255),
      location VARCHAR(255),
      documentname VARCHAR(255),
      contactnumber VARCHAR(255),
      containernumber INTEGER NOT NULL DEFAULT 0
    )
  `);
  console.log('Table `savings` is ready.');

  await pool.query(`
    CREATE TABLE IF NOT EXISTS collected (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      original_id BIGINT NOT NULL UNIQUE,
      fname VARCHAR(255),
      lname VARCHAR(255),
      nationalid VARCHAR(255),
      location VARCHAR(255),
      documentname VARCHAR(255),
      contactnumber VARCHAR(255),
      containernumber INTEGER NOT NULL DEFAULT 0,
      collected_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )
  `);
  console.log('Table `collected` is ready.');

  await pool.end();
}

init()
  .then(() => process.exit(0))
  .catch((err) => {
    console.error('Database initialization failed:', err.message);
    process.exit(1);
  });
